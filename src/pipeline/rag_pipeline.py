

from langchain_openai import ChatOpenAI
from langchain_openai.embeddings import OpenAIEmbeddings
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser
from pathlib import Path
from dotenv import load_dotenv

from src.logger import Logger
from src.prompt import Prompt
from src.indexing import Indexer
from src.data_ingestion import TranscriptFetcher
from src.retriever import Retriever
from src.interface.component_interface import ComponentInterface

load_dotenv()


class RAGPipeline(ComponentInterface):
    
    def __init__(self, retriever):
         self.logger = Logger(__name__, log_file="rag_pipeline.log", level="DEBUG").logger
         self.retriever = retriever
         self.prompt = Prompt()
         self.llm = ChatOpenAI(model_name="gpt-4.1-mini", temperature=0.2, max_tokens=2000)
         self.parser = StrOutputParser()

         self.chain = RunnablePassthrough.assign(
             context = lambda inputs : self._format_retrieved_chunks(
                 self.retriever.invoke(inputs["question"])
             )
         ) |  self.prompt.chat_prompt_template | self.llm | self.parser
         


    @staticmethod
    def _format_retrieved_chunks(documents):
        """
        Formats the retrieved chunks into a single string for input to the LLM.
        Arguments:
            chunks (List[str]): The list of retrieved transcript chunks.
        Returns:
            str: A single string containing all the retrieved chunks formatted for the LLM.
        """
        formatted_chunks = "\n\n".join(f"Source :{doc.metadata.get('source', 'Unknown')}\n" f"Content: {doc.page_content}" for doc in documents)
        return formatted_chunks
    
    def invoke(self, question: str, chat_history: list = None):
        """
        Invokes the RAG pipeline with the provided arguments.
        Arguments:
            *args: Positional arguments for the RAG pipeline.
            **kwargs: Keyword arguments for the RAG pipeline.
        Returns:
            str: The response generated by the RAG pipeline.
        """
        try:
            return self.chain.invoke({
            "question": question,
            "chat_history": chat_history or []
        })
        except Exception:
            self.logger.exception("RAG pipeline execution failed.")
            raise
    

